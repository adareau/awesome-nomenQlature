"""Generate the README contents, emoji legend and lists from the CSV files in
this folder, and write them into the README between the list-start and
list-end markers.

Usage:
    python data/generate_lists.py          # update README.md
    python data/generate_lists.py --check  # exit with an error if README.md is out of date
"""

import csv
import sys
from pathlib import Path

DATA_DIR = Path(__file__).parent
README = DATA_DIR.parent / "README.md"
START_MARKER = "<!-- list-start -->"
END_MARKER = "<!-- list-end -->"
NOTICE = "<!-- Generated by data/generate_lists.py: edit the CSV files in data/, not this section. -->"

EMOJIS_FILE = "emojis.csv"
SECTIONS = [
    ("Qompanies", "companies.csv"),
    ("ProduQts", "products.csv"),
    ("ProjeQts", "projects.csv"),
]
FIELDS = ["name", "url", "flag", "country", "description", "emojis"]


def read_csv(filename):
    with open(DATA_DIR / filename, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def to_markdown_name(name):
    """Bold every capital Q in the name."""
    return name.replace("Q", "**Q**")


def flag_to_country(flag):
    """Turn a flag emoji into its two-letter country code."""
    return "".join(chr(ord(c) - 0x1F1E6 + ord("A")) for c in flag)


def validate(filename, rows, legend):
    """Return a list of problems found in the rows of a CSV file."""
    errors = []
    seen = set()
    for line, row in enumerate(rows, start=2):
        where = f"{filename}:{line}"
        missing = [field for field in FIELDS if not (row.get(field) or "").strip()]
        if missing:
            errors.append(f"{where}: missing {', '.join(missing)}")
            continue
        name = row["name"]
        if name.casefold() in seen:
            errors.append(f"{where}: duplicate name {name!r}")
        seen.add(name.casefold())
        if "Q" not in name:
            errors.append(f"{where}: {name!r} has no capital Q")
        if flag_to_country(row["flag"]) != row["country"]:
            errors.append(f"{where}: flag {row['flag']} does not match country {row['country']!r}")
        for emoji in row["emojis"].split():
            if emoji not in legend:
                errors.append(f"{where}: emoji {emoji} is not in {EMOJIS_FILE}")
    return errors


def format_entry(row):
    name = to_markdown_name(row["name"])
    emojis = "|".join(row["emojis"].split())
    return f"- [{name}]({row['url']}) {row['flag']} - {row['description']}. {emojis}".rstrip()


def generate(sections, legend):
    contents = ["## Contents"] + [
        f"- [{to_markdown_name(title)}](#{title.lower()})" for title, _ in sections
    ]
    emojis = ["## Emoji Qlassification"] + [
        f"- {emoji} ⟩ {meaning}" for emoji, meaning in legend.items()
    ]
    blocks = [NOTICE, "\n".join(contents), "\n".join(emojis)]
    for title, rows in sections:
        rows = sorted(rows, key=lambda row: row["name"].casefold())
        blocks.append("\n".join([f"## {title}"] + [format_entry(row) for row in rows]))
    return "\n\n".join(blocks)


def replace_between_markers(text, content):
    start = text.index(START_MARKER) + len(START_MARKER)
    end = text.index(END_MARKER)
    return f"{text[:start]}\n{content}\n{text[end:]}"


def main():
    check = "--check" in sys.argv[1:]

    legend = {row["emoji"]: row["meaning"] for row in read_csv(EMOJIS_FILE)}
    errors = []
    sections = []
    for title, filename in SECTIONS:
        rows = read_csv(filename)
        errors += validate(filename, rows, legend)
        if rows:  # sections without entries are left out, contents included
            sections.append((title, rows))
    if errors:
        sys.exit("\n".join(errors))

    text = README.read_text(encoding="utf-8")
    new_text = replace_between_markers(text, generate(sections, legend))
    if check:
        if new_text != text:
            sys.exit("README.md is out of date: run python data/generate_lists.py")
        print("README.md is up to date")
    else:
        README.write_text(new_text, encoding="utf-8")


if __name__ == "__main__":
    main()
